/**
 * Builds the share site's privacy policy, one static page per language, from the app's own
 * texts (src/constants/legal*.ts): the site and the app always say the same thing.
 *
 *   npx --yes tsx scripts/build-site-legal.ts
 *
 * Writes share-site/confidentialite.html (fr), privacy.html (en), privacidad.html (es) and
 * aporrito.html (el). Run it again after changing the policy or the date below.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { privacyIn, PUBLISHER, type LegalSection } from '../src/constants/legal';
import type { Language } from '../src/lib/i18n';

/** The day the policy last changed, shown at the top of each page. */
const UPDATED = new Date(Date.UTC(2026, 9, 19));

const SITE = 'https://tier-list-app-share-site.vercel.app';
const APP_STORE = 'https://apps.apple.com/app/id6822017061';

type Page = {
  slug: string;
  /** Locale for the date ("en-US": the site's English is American). */
  locale: string;
  name: string;
  title: string;
  updated: string;
  languages: string;
  download: string;
  home: string;
  support: string;
  contact: string;
};

// Labels as the app writes them (app.settings.privacy, app.settings.support, app.results.home).
const PAGES: Record<Language, Page> = {
  fr: { slug: 'confidentialite', locale: 'fr-FR', name: 'Français', title: 'Politique de confidentialité', updated: 'Dernière mise à jour : {date}', languages: 'Langue', download: 'Télécharger', home: 'Accueil', support: 'Assistance', contact: 'Contact' },
  en: { slug: 'privacy', locale: 'en-US', name: 'English', title: 'Privacy policy', updated: 'Last updated: {date}', languages: 'Language', download: 'Download', home: 'Home', support: 'Support', contact: 'Contact' },
  es: { slug: 'privacidad', locale: 'es-ES', name: 'Español', title: 'Política de privacidad', updated: 'Última actualización: {date}', languages: 'Idioma', download: 'Descargar', home: 'Inicio', support: 'Soporte', contact: 'Contacto' },
  el: { slug: 'aporrito', locale: 'el-GR', name: 'Ελληνικά', title: 'Πολιτική απορρήτου', updated: 'Τελευταία ενημέρωση: {date}', languages: 'Γλώσσα', download: 'Λήψη', home: 'Αρχική', support: 'Υποστήριξη', contact: 'Επικοινωνία' },
};

const LANGUAGES = Object.keys(PAGES) as Language[];

const escape = (text: string) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** A text of the policy, escaped, its contact address made a link. */
const prose = (text: string) => escape(text).split(PUBLISHER.email).join(`<a href="mailto:${PUBLISHER.email}">${PUBLISHER.email}</a>`);

const section = ({ title, paragraphs = [], bullets = [] }: LegalSection) =>
  [
    `    <h2>${escape(title)}</h2>`,
    ...paragraphs.map((p) => `    <p>${prose(p)}</p>`),
    ...(bullets.length ? ['    <ul>', ...bullets.map((b) => `      <li>${prose(b)}</li>`), '    </ul>'] : []),
  ].join('\n');

function page(lang: Language): string {
  const p = PAGES[lang];
  const sections = privacyIn(lang);
  const date = new Intl.DateTimeFormat(p.locale, { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }).format(UPDATED);
  // The home and support pages pick their language from the browser: ?lang= keeps the reader's.
  const local = (path: string) => `${path}?lang=${lang}`;
  const switcher = LANGUAGES.map((l) =>
    l === lang
      ? `<span aria-current="page">${PAGES[l].name}</span>`
      : `<a href="/${PAGES[l].slug}" hreflang="${l}" lang="${l}">${PAGES[l].name}</a>`,
  ).join('');
  const alternates = LANGUAGES.map((l) => `  <link rel="alternate" hreflang="${l}" href="${SITE}/${PAGES[l].slug}">`).join('\n');

  return `<!doctype html>
<!-- Generated by scripts/build-site-legal.ts from src/constants/legal*.ts: edit those, not this page. -->
<html lang="${lang}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <title>${escape(p.title)} · Tiercraft</title>
  <meta name="description" content="${escape(sections[0]?.paragraphs?.[0] ?? p.title)}">
  <link rel="icon" href="/icon.png">
  <meta name="theme-color" content="#0B0C12">
${alternates}
  <link rel="alternate" hreflang="x-default" href="${SITE}/${PAGES.en.slug}">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Inter:wght@500;600;700;800;900&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="/site.css">
  <style>
    .langs { display: flex; flex-wrap: wrap; gap: 8px; margin: 16px 0 8px; font-size: 14px; font-weight: 700; }
    .langs a, .langs span { padding: 6px 12px; border-radius: 999px; border: 1px solid var(--border); background: var(--surface); color: var(--muted); text-decoration: none; }
    .langs a:hover { color: var(--text); border-color: var(--primary); }
    .langs span { color: var(--text); border-color: var(--primary); }
    .page li { margin: 6px 0; }
  </style>
</head>
<body>
  <div class="glow"></div>
  <header class="top">
    <a class="brand" href="${local('/')}"><img src="/icon.png" alt=""><span><b>Tiercraft</b><span class="strip"><i></i><i></i><i></i><i></i><i></i></span></span></a>
    <a class="btn small" href="${APP_STORE}">${escape(p.download)}</a>
  </header>
  <main class="page">
    <h1>${escape(p.title)}</h1>
    <p class="muted">${escape(p.updated.replace('{date}', date))}</p>
    <nav class="langs" aria-label="${escape(p.languages)}">${switcher}</nav>

${sections.map(section).join('\n\n')}
  </main>
  <footer>
    <span>© ${UPDATED.getUTCFullYear()} ${escape(PUBLISHER.name)}</span>
    <nav><a href="${local('/')}">${escape(p.home)}</a><a href="${local('/support')}">${escape(p.support)}</a><a href="mailto:${PUBLISHER.email}">${escape(p.contact)}</a></nav>
  </footer>
  <script src="/site.js" defer></script>
</body>
</html>
`;
}

const dir = join(__dirname, '..', 'share-site');
for (const lang of LANGUAGES) {
  const file = join(dir, `${PAGES[lang].slug}.html`);
  writeFileSync(file, page(lang));
  console.log(`${lang} → ${file}`);
}
