def q(s):
    return "'" + s.replace("'", "''") + "'"

def main():
    print("-- Images of the daily tier lists (scripts/daily-concepts.py): the library concept of each")
    print("-- card, in the order of its items, and the card shown as the list's picture (cover).")
    print("alter table public.daily_lists add column if not exists concepts text[];")
    print("alter table public.daily_lists add column if not exists cover smallint;")
    print()
    for day, (cover, concepts) in DAYS.items():
        arr = "array[" + ", ".join(q(c) for c in concepts.split()) + "]"
        print(f"update public.daily_lists set concepts = {arr}, cover = {cover}")
        print(f"  where day = {q(day)} and array_length(items, 1) = {len(concepts.split())};")

if __name__ == "__main__":
    main()
