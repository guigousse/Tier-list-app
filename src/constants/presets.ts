import { TIER_COLORS } from './theme';

/** Default tiers of every new tier list. */
export const CLASSIC_TIERS = ['S', 'A', 'B', 'C', 'D'];

export function tierColorAt(index: number): string {
  return TIER_COLORS[index % TIER_COLORS.length];
}

export type Template = {
  key: string;
  title: string;
  emoji: string;
  items: string[];
  /** Tier labels to start with instead of the user's default preset. */
  tiers?: string[];
  /** Per item: App Store id whose icon becomes the card picture. */
  appStoreIds?: (number | undefined)[];
  /** Per item: tier index the card starts in (-1 or missing: to rank). */
  ranks?: number[];
  /** For a past daily tier list: its day (YYYY-MM-DD). */
  day?: string;
  /**
   * Per item: concept of its image in the shared AI library (English slug, as the
   * server writes them: "red-apple"), drawn once and reused by every list.
   */
  concepts?: string[];
  /** Grand theme the list is shown under in the gallery of public tier lists. */
  theme?: string;
};

/**
 * A public list written card by card: its name and the concept of its image in the
 * shared AI library. The cards of a public list are only ever added to, never renamed:
 * the players' copies find their cards by name (lib/publicSync.ts).
 */
function publicList(list: Omit<Template, 'items' | 'concepts'> & { cards: [string, string][] }): Template {
  const { cards, ...rest } = list;
  return { ...rest, items: cards.map(([label]) => label), concepts: cards.map(([, concept]) => concept) };
}

