-- Public tier lists, richer (src/lib/themes.ts, src/lib/publicSync.ts): a template
-- carries its grand theme and, card by card, the concept of its image in the shared AI
-- library. The app reads the images already drawn for free (get_card_icons): nothing is
-- drawn there, and only images, no player data.
--
-- The three templates published online get 20 cards, ranks that speak of their theme and
-- their concepts, the cards already there kept word for word (players' copies find their
-- cards by name). Concepts not drawn yet join the wishlist: free cells of later sheets
-- draw them.

alter table public.templates add column if not exists concepts text[];
alter table public.templates add column if not exists theme text;
alter table public.templates add constraint templates_concepts_match
  check (concepts is null or cardinality(concepts) = cardinality(items));

create or replace function public.get_card_icons(concepts text[])
 returns table(concept text, image text)
 language plpgsql
 stable
 security definer
 set search_path to ''
as $$
begin
  perform private.hit('get_card_icons', 300);
  return query
    select ci.concept, ci.image from public.card_icons ci
    where ci.concept = any (get_card_icons.concepts[1:400]) and ci.image is not null;
end;
$$;
